/** Language chosen by the layout (e.g. a Polish Luma export), ahead of the HA user language. */
const [preferredLang, setPreferredLangSignal] = createSignal<string | undefined>();
export const setPreferredLang = (lang: string | undefined) => setPreferredLangSignal(lang);

export function pickLang(hass: Hass | undefined): Lang {
  const forced = new URLSearchParams(location.search).get("lang");
  const raw = (forced ?? preferredLang() ?? hass?.language ?? hass?.locale?.language ?? navigator.language ?? "en").toLowerCase();
  if (raw.startsWith("pl")) return "pl";
  if (raw.startsWith("de")) return "de";
  return "en";
}

/** Context-free lookup for code that runs outside the Krystal provider. */
export function translate(lang: Lang, key: TKey, vars?: Record<string, string | number>): string {
  let text = dicts[lang][key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

export interface Translator {
  (key: TKey, vars?: Record<string, string | number>): string;
  lang: () => Lang;
  condition: (state: string | undefined) => string;
}

export function useT(): Translator {
  const hass = useHass();
  const lang = createMemo(() => pickLang(hass()));
  const t = ((key: TKey, vars?: Record<string, string | number>) => translate(lang(), key, vars)) as Translator;
  t.lang = lang;
  t.condition = (state) => (state ? conditions[lang()][state] ?? state : "—");
  return t;
}
